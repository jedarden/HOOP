/// Spawn a subprocess that generates multiple lines of output
pub fn spawn_multi_line_subprocess(line_count: usize) -> SubprocessResult {
    let config = SubprocessConfig {
        output_type: OutputType::Both,
        line_count,
        prefix: "MULTI_LINE".to_string(),
        ..Default::default()
    };

    // For multi-line output, we'll use a loop in a shell script
    let shell_script = format!(
        "for i in $(seq 1 {}); do echo '{}_line_$i' && echo '{}_err_$i' >&2; done",
        line_count, config.prefix, config.prefix
    );

    let mut command = Command::new("sh");
    command.arg("-c");
    command.arg(shell_script);
    command.stdout(Stdio::piped());
    command.stderr(Stdio::piped());

    let output = command
        .output()
        .expect("Failed to execute multi-line subprocess");

    let success = output.status.success();
    let exit_code = output.status.code();
    let stdout = String::from_utf8_lossy(&output.stdout).to_string();
    let stderr = String::from_utf8_lossy(&output.stderr).to_string();

    SubprocessResult::new(success, exit_code, stdout, stderr)
}

